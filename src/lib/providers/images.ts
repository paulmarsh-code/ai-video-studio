// Image provider layer (decision D15).
// Today: manual — the app writes the GPT prompt, the user generates in ChatGPT and uploads.
// Later: set OPENAI_API_KEY (and optionally OPENAI_IMAGE_MODEL) and a "Generate" button
// appears beside each upload. The same interface can be backed by an MCP connector.
// The app never claims an image was generated unless a provider actually returned one.

export interface GeneratedImage {
  data: Buffer;
  mime: string;
  providerNote: string;
}

export interface ImageProvider {
  id: string;
  label: string;
  generate(prompt: string, refs: { data: Buffer; mime: string; name: string }[], size: "portrait" | "landscape" | "square"): Promise<GeneratedImage>;
}

const SIZES = { portrait: "1024x1536", landscape: "1536x1024", square: "1024x1024" } as const;

/** OpenAI Images API. Untested in the build environment (no key, no network): verify with a real key before relying on it. */
export function openAIProvider(apiKey: string, model = process.env.OPENAI_IMAGE_MODEL || "gpt-image-1"): ImageProvider {
  return {
    id: "openai",
    label: `OpenAI ${model}`,
    async generate(prompt, refs, size) {
      let res: Response;
      if (refs.length) {
        const form = new FormData();
        form.set("model", model);
        form.set("prompt", prompt);
        form.set("size", SIZES[size]);
        for (const r of refs) form.append("image[]", new Blob([new Uint8Array(r.data)], { type: r.mime }), r.name);
        res = await fetch("https://api.openai.com/v1/images/edits", { method: "POST", headers: { Authorization: `Bearer ${apiKey}` }, body: form });
      } else {
        res = await fetch("https://api.openai.com/v1/images/generations", {
          method: "POST",
          headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
          body: JSON.stringify({ model, prompt, size: SIZES[size] }),
        });
      }
      if (!res.ok) throw new Error(`OpenAI image request failed (${res.status}): ${(await res.text()).slice(0, 300)}`);
      const body = (await res.json()) as { data?: { b64_json?: string }[] };
      const b64 = body.data?.[0]?.b64_json;
      if (!b64) throw new Error("OpenAI returned no image data.");
      return { data: Buffer.from(b64, "base64"), mime: "image/png", providerNote: `Generated by ${model}` };
    },
  };
}

/** The configured provider, or null for manual upload only. */
export function getImageProvider(): ImageProvider | null {
  const key = process.env.OPENAI_API_KEY;
  return key ? openAIProvider(key) : null;
}

// ---- Describe (D16): turn a picture or an idea into labelled fields ----

export interface TextProvider {
  id: string;
  label: string;
  /** Run the prompt, with an optional image, and return the model's text reply. */
  describe(prompt: string, image?: { data: Buffer; mime: string }): Promise<string>;
}

/** OpenAI Chat Completions with image input. Untested in the build environment: verify with a real key. */
export function openAITextProvider(apiKey: string, model = process.env.OPENAI_TEXT_MODEL || "gpt-4o"): TextProvider {
  return {
    id: "openai",
    label: `OpenAI ${model}`,
    async describe(prompt, image) {
      const content: unknown[] = [{ type: "text", text: prompt }];
      if (image) content.push({ type: "image_url", image_url: { url: `data:${image.mime};base64,${image.data.toString("base64")}` } });
      const res = await fetch("https://api.openai.com/v1/chat/completions", {
        method: "POST",
        headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
        body: JSON.stringify({ model, messages: [{ role: "user", content }] }),
      });
      if (!res.ok) throw new Error(`OpenAI request failed (${res.status}): ${(await res.text()).slice(0, 300)}`);
      const body = (await res.json()) as { choices?: { message?: { content?: string } }[] };
      const text = body.choices?.[0]?.message?.content;
      if (!text) throw new Error("OpenAI returned no text.");
      return text;
    },
  };
}

export function getTextProvider(): TextProvider | null {
  const key = process.env.OPENAI_API_KEY;
  return key ? openAITextProvider(key) : null;
}
